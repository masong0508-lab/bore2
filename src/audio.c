int audio_cd_load(const char *name, void *dst, int room) {   // a whole file from the disc into RAM (an overlay); 0 if it is not there or does not fit
    if (!cd_up) return 0;
    extern unsigned char arun[]; arun[3] = 1;
    char path[24]; snprintf(path, sizeof path, "\\%s;1", name);
    CdlFILE f; if (!CdSearchFile(&f, path)) return 0; arun[3] = 2;
    int secs = (int)((f.size + 2047) / 2048); if (secs * 2048 > room) { arun[3] = 8; return 0; } arun[4] = (unsigned char)secs;
    if (!CdControl(CdlSetloc, &f.pos, 0)) return 0; arun[3] = 3;
    if (!CdRead(secs, (u32 *)dst, CdlModeSpeed)) return 0; arun[3] = 4;
    { int r = CdReadSync(0, 0) >= 0; arun[3] = 5; return r; }
}
int audio_cd_part(const char *name, u32 sector, int count, void *dst) {   // some sectors from inside a file (one picture of a big art file at a time)
    if (!cd_up) return 0;
    char path[24]; snprintf(path, sizeof path, "\\%s;1", name);
    CdlFILE f; if (!CdSearchFile(&f, path)) return 0;
    CdlLOC loc; CdIntToPos(CdPosToInt(&f.pos) + (int)sector, &loc);
    if (!CdControl(CdlSetloc, &loc, 0)) return 0;
    if (!CdRead(count, (u32 *)dst, CdlModeSpeed)) return 0;
    return CdReadSync(0, 0) >= 0;
}
int audio_cd_peek(const char *name, void *dst) {   // the first 2048 bytes of a file on the disc (is a pack really there?); 0 if it cannot be read
    if (!cd_up) return 0;
    char path[24]; snprintf(path, sizeof path, "\\%s;1", name);
    CdlFILE f; if (!CdSearchFile(&f, path)) return 0;
    if (!CdControl(CdlSetloc, &f.pos, 0)) return 0;
    if (!CdRead(1, (u32 *)dst, CdlModeSpeed)) return 0;
    return CdReadSync(0, 0) >= 0;
}
static int cd_read(u32 sector, int count, void *buf) {
    CdlLOC loc;
    CdIntToPos(CdPosToInt(&songs_loc) + (int)sector, &loc);
    if (!CdControl(CdlSetloc, &loc, 0)) return 0;
    if (!CdRead(count, (u32 *)buf, CdlModeSpeed)) return 0;
    return CdReadSync(0, 0) >= 0;
}


// ---- THE STREAMER: a recorded song (no notes to sequence) played straight off the disc (tools/build_streams.py) ----
// On the disc: chunks of 4 KB of left then 4 KB of right ADPCM; every 4 KB ends with the end + repeat flags. Two buffers of one chunk sit
// in sound memory (where a sequenced song's samples would go); voices 0 and 1 play one while the other is filled. The SPU raises its IRQ
// as a voice starts on a buffer: the handler points both voices' loop address at the other buffer and fills it from a FIFO in RAM (the
// sequence buffer, idle while a stream plays); the main loop keeps the FIFO topped up from the disc (audio_update, a few sectors a time).
#define ST_IL    4096                                  // bytes per channel per chunk
#define ST_CH    (2 * ST_IL)                           // a chunk: left then right (4 sectors)
#define ST_NF    (SEQ_MAX / ST_CH)                     // chunks the FIFO holds (11: about 2.5 s at 32 kHz)
static volatile int st_on, st_db, st_n, st_tail, st_done, st_under;
static int st_head, st_reading, st_read, st_total, st_sector, st_rate;
static void *st_old_irq, *st_old_dma;
static void st_irq(void) {
    SPU_CTRL &= ~(1 << 6);                              // (the only way to acknowledge it: off now, on again once the buffer is filled)
    if (!st_on) return;
    if (!st_n) {                                        // the FIFO is empty
        if (st_read >= st_total && !st_reading) { st_done = 1; SPU_KEY_OFF1 = 3; return; }   // the end of the song
        st_under++; SPU_CTRL |= 1 << 6; return;         // (the disc is behind: the last buffer plays again)
    }
    st_db ^= 1;
    const u8 *ptr = (const u8 *)seqbuf + st_tail * ST_CH;
    st_tail = (st_tail + 1) % ST_NF; st_n--;
    int addr = song_base + st_db * ST_CH;
    SpuSetTransferStartAddr(addr);
    SPU_IRQ_ADDR = getSPUAddr(addr);                    // (the IRQ again when a voice starts on this buffer)
    SPU_CH_LOOP_ADDR(0) = getSPUAddr(addr); SPU_CH_LOOP_ADDR(1) = getSPUAddr(addr + ST_IL);
    SpuWrite((const u32 *)ptr, ST_CH);
}
static void st_dma(void) { if (st_on) SPU_CTRL |= 1 << 6; }
static void st_feed(void) {                            // (main loop) the disc into the FIFO: a read of up to 4 chunks at a time
    if (!st_on) return;
    if (st_reading) {
        int r = CdReadSync(1, 0);
        if (r > 0) return;
        if (r == 0) { EnterCriticalSection(); st_head = (st_head + st_reading) % ST_NF; st_n += st_reading; ExitCriticalSection(); st_read += st_reading; }
        st_reading = 0;                                 // (an error: the same chunks are asked for again)
    }
    int free_ = ST_NF - st_n, k = MIN(MIN(free_, ST_NF - st_head), MIN(4, st_total - st_read));
    if (k <= 0) return;
    CdlLOC loc; CdIntToPos(CdPosToInt(&songs_loc) + st_sector + st_read * (ST_CH / 2048), &loc);
    if (!CdControl(CdlSetloc, &loc, 0)) return;
    if (CdRead(k * (ST_CH / 2048), (u32 *)((u8 *)seqbuf + st_head * ST_CH), CdlModeSpeed)) st_reading = k;
}
static void st_stop(void) {
    if (!st_on) return;
    EnterCriticalSection();
    st_on = 0; SPU_CTRL &= ~(1 << 6);
    InterruptCallback(IRQ_SPU, st_old_irq); DMACallback(DMA_SPU, st_old_dma);
    ExitCriticalSection();
    SpuIsTransferCompleted(SPU_TRANSFER_WAIT);
    SPU_KEY_OFF1 = 3; SPU_CH_VOL_L(0) = SPU_CH_VOL_R(0) = SPU_CH_VOL_L(1) = SPU_CH_VOL_R(1) = 0;
    SPU_CH_ADDR(0) = SPU_CH_ADDR(1) = getSPUAddr(0x1000);   // (the dummy block: a stopped voice still reads, and must not trip the IRQ)
    if (st_reading) { CdReadSync(0, 0); st_reading = 0; }
}
static int st_start(int i) {                           // (after music_silence) 1: playing
    st_sector = (int)sidx[i].sector; st_total = (int)sidx[i].smp_bytes; st_rate = songs[i].rate ? songs[i].rate : 32000;
    st_head = st_tail = st_n = st_read = st_reading = 0; st_db = 1; st_done = 0; st_under = 0;
    for (int ch = 0; ch < MUS_CH; ch++) SPU_CH_ADDR(ch) = getSPUAddr(0x1000);
    int first = MIN(ST_NF, st_total);                  // the FIFO full before the first note
    if (!cd_read((u32)st_sector, first * (ST_CH / 2048), seqbuf)) return 0;
    st_head = first % ST_NF; st_n = first; st_read = first;
    SpuSetTransferMode(SPU_TRANSFER_BY_DMA);
    EnterCriticalSection();
    st_old_irq = InterruptCallback(IRQ_SPU, &st_irq); st_old_dma = DMACallback(DMA_SPU, &st_dma);
    st_on = 1;
    ExitCriticalSection();
    st_irq(); SpuIsTransferCompleted(SPU_TRANSFER_WAIT);   // the first chunk into a buffer
    SPU_CTRL &= ~(1 << 6);                              // (no IRQ as the voices start on it: the second chunk is sent by hand below)
    int addr = song_base + st_db * ST_CH, v = 0x3fff * music_vol / 320;
    SPU_KEY_OFF1 = 3;
    for (int c = 0; c < 2; c++) {
        SPU_CH_ADDR(c) = getSPUAddr(addr + c * ST_IL); SPU_CH_FREQ(c) = getSPUSampleRate(st_rate);
        SPU_CH_ADSR1(c) = 0x00ff; SPU_CH_ADSR2(c) = 0x0000;
        SPU_CH_VOL_L(c) = c ? 0 : v; SPU_CH_VOL_R(c) = c ? v : 0;
    }
    SPU_REVERB_ON1 = 0;                                 // (the recording has its own room)
    SPU_KEY_ON1 = 3;
    st_irq();                                           // the second chunk into the other buffer; the IRQ armed on it
    return 1;
}
void audio_jukebox_stop(void) {
    st_stop();
    music_silence();
    cur_song = -1;
}
void audio_jukebox_play(int i) {
    if (!cd_ok || i < 0 || i >= NSONGS) return;
    st_stop();
    music_silence();
    cur_song = -1;
    if (songs[i].stream) { if (st_start(i)) { play_frames = 0; cur_song = i; } return; }
    if (song_base + (int)sidx[i].smp_bytes > REV_ADDR) return;     // (never into the reverb's work area)
    // the samples: through the sequence buffer, a chunk at a time, into sound memory after the voices
    int left = (int)sidx[i].smp_sectors, sec = (int)(sidx[i].sector + sidx[i].seq_sectors), addr = song_base;
    while (left > 0) {
        int n = left > SEQ_MAX / 2048 ? SEQ_MAX / 2048 : left;
        if (!cd_read((u32)sec, n, seqbuf)) return;
        spu_write(addr, seqbuf, n * 2048);
        addr += n * 2048; sec += n; left -= n;
    }
    // the sequence
    if ((int)sidx[i].seq_sectors * 2048 > 36864 || !cd_read(sidx[i].sector, (int)sidx[i].seq_sectors, seqbuf)) return;
    if (!deck_setup(&dk[0], (const u8 *)seqbuf, song_base, 0)) return;
    play_frames = 0; cur_song = i;
    reverb_set(songs[i].fx);
    dk[0].gain = 256; dk[0].on = 1;
}
// ---- THE DJ: eight of the songs, cut down to short excerpts, on two tracker decks ----
// Everything is still the tracker: the songs' own notes and samples, played by the sound chip. A deck holds one song's excerpt (a minute at
// most) and loops it; the other deck can be cued while the first plays (its samples come off the disc a few sectors a frame, so nothing
// hitches), then launched on the first deck's next order, with its tempo squeezed to match (a tracker stretches time for free: the notes
// only come faster). The crossfade, the tricks (echo, brake, scratch, drop, killing a part of the song) are all done on the decks' volumes,
// tempo, pitch and muted channels. dj_ui.c (the overlay DJ.OVL) is the booth; how well it all goes is its business (the hidden skill).
#define DJ_N 8
typedef unsigned long long u64;
static int station;
// bars: the usual excerpt (about a minute); maxord: the most orders a deck may be given (3 x that: a master's long ride); sect: the sectors of
// the song's sequence block that reach that far (worked out by tools/dj_sizes.py from the packed notes)
static const struct { const char *song, *mix; u8 bars, maxord, sect; } djt[DJ_N] = {
    { "THE CYNICAL SYNDICATION", "SYNDICATION OF SMIRKS", 20, 64, 6 }, { "MISTER QUICKBULLET", "QUICKBULLET RUSH", 16, 51, 7 },
    { "HOT DAMN", "HOT DAMN, HOT DAMN!", 16, 51, 6 },               { "WORTHLESS CLOUDS", "PRICELESS CLOUDS", 16, 51, 7 },
    { "AIM AND SHOOT", "AIM, SHOOT, DANCE", 10, 29, 4 },            { "OHIO HOE", "OH-HI-OH HOE-DOWN", 20, 57, 6 },
    { "GOTTCHO BARRACHO", "GOTTCHA BARRA-KILLER", 20, 62, 5 },     { "AN ODE TO THE SPANISH FLEXICODE", "FLEXICODE FIESTA", 20, 46, 4 } };
// (RAM is tight: both decks' notes sit in the jukebox's own sequence buffer, 16 KB each - only the first part of a song, as much as its excerpt can reach, is read - and the samples pass through the last 8 KB of it)
#define DJ_SEQ(d)  ((u8 *)seqbuf + (d) * 16384)
#define DJ_STAGE   ((u8 *)seqbuf + 32768)
static int dj_st[2], dj_tr[2] = { -1, -1 }, dj_song_ix[DJ_N] = { -1 };
static struct { int busy, deck, track, phase, left, sec, addr, n, bars; } ld;
#define DJ_SLOT 98304                                   // each deck's room for samples (the biggest excerpt song is 93808)
int dj_count(void) { return DJ_N; }
const char *dj_track_name(int t) { return t >= 0 && t < DJ_N ? djt[t].mix : ""; }
const char *dj_track_real(int t) { return t >= 0 && t < DJ_N ? djt[t].song : ""; }
static void dj_resolve(void) {
    if (dj_song_ix[0] >= 0 && dj_song_ix[1] != -2) { if (dj_song_ix[0] != -1) return; }
    for (int t = 0; t < DJ_N; t++) { dj_song_ix[t] = -2; for (int i = 0; i < NSONGS; i++) if (!strcmp(songs[i].name, djt[t].song)) { dj_song_ix[t] = i; break; } }
}
int dj_active(void) { return dj_mode; }
void dj_begin(void) {
    if (!cd_ok) return;
    if (dj_mode) return;
    st_stop(); music_silence(); cur_song = -1; station = -1;
    dj_resolve(); dj_st[0] = dj_st[1] = 0; dj_tr[0] = dj_tr[1] = -1; ld.busy = 0; dj_wash = 0;
    for (int v = 0; v < MUS_CH; v++) { vdeck[v] = 0; vtime[v] = 0; }
    reverb_set(1); dj_mode = 1;
}
int dj_state(int d) { return dj_st[d & 1]; }                 // 0 empty, 1 loading, 2 ready, 3 playing
int dj_track(int d) { return dj_tr[d & 1]; }
int dj_bars(int t) { return t >= 0 && t < DJ_N ? djt[t].bars : 0; }
int dj_cue(int d, int t, int bars) {                                   // start reading a track onto a deck that is not playing (1: started)
    d &= 1; if (!dj_mode || ld.busy || dj_st[d] == 3 || t < 0 || t >= DJ_N || dj_song_ix[t] < 0) return 0;
    dk[d].on = 0; dk[d].pending = 0;
    dj_st[d] = 1; dj_tr[d] = t; ld.bars = bars < 4 ? 4 : bars > djt[t].maxord ? djt[t].maxord : bars; ld.busy = 1; ld.deck = d; ld.track = t; ld.phase = 0;
    return 1;
}
static void dj_pump(void) {
    if (!ld.busy) return;
    int i = dj_song_ix[ld.track], d = ld.deck; u8 *buf = DJ_SEQ(d);
    if (ld.phase == 0) {
        CdlLOC loc; CdIntToPos(CdPosToInt(&songs_loc) + (int)sidx[i].sector, &loc);
        if (!CdControl(CdlSetloc, &loc, 0) || !CdRead(djt[ld.track].sect, (u32 *)buf, CdlModeSpeed)) { ld.busy = 0; dj_st[d] = 0; return; }
        ld.phase = 1; return;
    }
    if (ld.phase == 1 || ld.phase == 3) {
        int r = CdReadSync(1, 0); if (r > 0) return;
        if (r < 0) { ld.busy = 0; dj_st[d] = 0; return; }
        if (ld.phase == 1) { ld.left = (int)sidx[i].smp_sectors; ld.sec = (int)(sidx[i].sector + sidx[i].seq_sectors); ld.addr = d ? song_base + DJ_SLOT : song_base; }
        else { spu_write(ld.addr, DJ_STAGE, ld.n * 2048); ld.addr += ld.n * 2048; ld.sec += ld.n; ld.left -= ld.n; }
        if (ld.left <= 0) {
            int base = d ? song_base + DJ_SLOT : song_base;
            if (!deck_setup(&dk[d], buf, base, 1)) { ld.busy = 0; dj_st[d] = 0; return; }
            if (dk[d].loop_ord + ld.bars < dk[d].end_ord) dk[d].end_ord = dk[d].loop_ord + ld.bars;
            dk[d].gain = 0; ld.busy = 0; dj_st[d] = 2; return;
        }
        ld.phase = 2;
    }
    if (ld.phase == 2) {
        ld.n = ld.left > 2 ? 2 : ld.left;
        CdlLOC loc; CdIntToPos(CdPosToInt(&songs_loc) + ld.sec, &loc);
        if (!CdControl(CdlSetloc, &loc, 0) || !CdRead(ld.n, (u32 *)DJ_STAGE, CdlModeSpeed)) { ld.busy = 0; dj_st[d] = 0; return; }
        ld.phase = 3;
    }
}
static void dj_apply_gain(int d) {
    Deck *k = &dk[d]; int g = k->gain;
    for (int v = 0; v < MUS_CH; v++) if (vdeck[v] == d + 1) { SPU_CH_VOL_L(v) = vbl[v] * g >> 8; SPU_CH_VOL_R(v) = vbr[v] * g >> 8; }
}
void dj_fader(int d, int g) { d &= 1; dk[d].gain = CLAMP(g, 0, 256); dj_apply_gain(d); }
int  dj_gain(int d) { return dk[d & 1].gain; }
void dj_set_tempo(int d, int t) { d &= 1; t = CLAMP(t, 20, 700); dk[d].tempo = t; dk[d].rowlen = (u32)(((u64)dk[d].rowlen0 * 256) / (u32)t); }
int  dj_tempo(int d) { return dk[d & 1].tempo; }
int  dj_order_ms(int d) {                                     // how long one order (a bar) lasts on a deck, as it plays now
    Deck *k = &dk[d & 1]; if (!k->sq) return 0;
    u64 rl = (u64)k->rowlen * k->rows[k->order[k->ord]]; return (int)(rl * 1000 / ((u64)MIXR * 256 * TICK_HZ));
}
int dj_order_ms0(int d) {                                     // ... at the song's own tempo
    Deck *k = &dk[d & 1]; if (!k->sq) return 0;
    u64 rl = (u64)k->rowlen0 * k->rows[k->order[k->loop_ord]]; return (int)(rl * 1000 / ((u64)MIXR * 256 * TICK_HZ));
}
void dj_sync(int d, int err) {                                 // squeeze deck d's tempo to the other deck's bar (err: 8.8 off, a bad hand); the half or double of it if that is nearer
    d &= 1; Deck *k = &dk[d], *m = &dk[d ^ 1]; if (!k->sq || !m->sq) return;
    int mm = dj_order_ms(d ^ 1), my = dj_order_ms0(d); if (mm <= 0 || my <= 0) return;
    int best = 256, bd = 1 << 30;
    for (int q = 0; q < 3; q++) { int tgt = q == 0 ? mm / 2 : q == 1 ? mm : mm * 2; int t = (int)((u64)256 * my / (u32)tgt); int dd = ABS(t - 256); if (dd < bd) { bd = dd; best = t; } }
    best = CLAMP(best, 160, 400);
    dj_set_tempo(d, best * (256 + err) / 256);
}
void dj_launch(int d, int cue_row) {                           // 1: the deck that is ready starts, on the playing deck's next order (cue_row rows into it: a late hand)
    d &= 1; Deck *k = &dk[d]; if (dj_st[d] != 2) return;
    dj_st[d] = 3; k->mute = 0; k->pmul = 256;
    if (dk[d ^ 1].on) { k->cue_row = cue_row < 0 ? 0 : cue_row; k->pending = 1; }
    else { k->acc = k->rowlen - MIXR * 256; k->on = 1; }
    cur_song = dj_song_ix[dj_tr[d]];
}
int dj_pending(int d) { return dk[d & 1].pending; }
void dj_stop(int d) {
    d &= 1; dk[d].on = 0; dk[d].pending = 0; dj_st[d] = 0; dj_tr[d] = -1;
    for (int v = 0; v < MUS_CH; v++) if (vdeck[v] == d + 1) { SPU_KEY_OFF1 = (u16)(1u << v); vdeck[v] = 0; }
    if (dk[d ^ 1].on) cur_song = dj_song_ix[dj_tr[d ^ 1]];
}
void dj_mute(int d, int mask) {                                // channels 0..15 of the deck silenced (the part of the song "killed")
    d &= 1; int fresh = mask & ~dk[d].mute; dk[d].mute = mask;
    for (int v = 0; v < MUS_CH; v++) if (vdeck[v] == d + 1 && (fresh & (1 << vtch[v]))) SPU_KEY_OFF1 = (u16)(1u << v);
}
int  dj_mutemask(int d) { return dk[d & 1].mute; }
void dj_pitch(int d, int pm) {                                 // a scratch: 8.8 pitch on the deck's sounding notes
    d &= 1; pm = CLAMP(pm, 16, 1024); dk[d].pmul = pm;
    for (int v = 0; v < MUS_CH; v++) if (vdeck[v] == d + 1) { int f = vfreq[v] * pm >> 8; SPU_CH_FREQ(v) = f > 0x3fff ? 0x3fff : f; }
}
void dj_echo(int on) { dj_wash = on; if (dj_mode) { int v = on ? 0x5200 : revFx[1].send; SPU_REVERB_VOL_L = v; SPU_REVERB_VOL_R = v; } }
int  dj_pos(int d, int what) { Deck *k = &dk[d & 1]; return what == 0 ? k->ord - k->loop_ord : what == 1 ? k->row : what == 2 ? (k->sq ? k->rows[k->order[k->ord]] : 1) : what == 3 ? k->end_ord - k->loop_ord : what == 4 ? k->bars : what == 5 ? k->act : k->on; }

// ---- RADIO STATIONS: the songs grouped by feel; a radio, stereo or jukebox tunes one in ----
static const char *const stNm[4] = { "BORE FM", "RAVE 101", "CHILL WAVE", "SPACE RADIO" };
static const char *const stKey[4] = { "DIPPER|EXCUSES|CORA|BARRACHO|FLEXICODE|WINNER|CIGARETTE",
                                      "HOT DAMN|COCAINE|CYNICAL|EMERGENCY|AIM AND|CONDENSED|OHIO|OVER MY VOICE",
                                      "TREE|CLOUDS|SUNMAN|WHISTLER|CLOSER|HERE TODAY",
                                      "SPACE|MARS|BOMB|MAGIC|NURSERY|STAGED|AMIGA|QUICKBULLET" };
static int station = -1;
static int in_station(int st, int i) {   // does song i's name hold one of the station's words
    const char *k = stKey[st], *n = songs[i].name;
    while (*k) { char w[16]; int l = 0; while (*k && *k != '|' && l < 15) w[l++] = *k++; w[l] = 0; if (*k == '|') k++;
                 if (strstr(n, w)) return 1; }
    return 0;
}
int audio_station_count(void) { return 4; }
const char *audio_station_name(int s) { return s >= 0 && s < 4 ? stNm[s] : "OFF"; }
int audio_station(void) { return station; }
void audio_station_play(int s) {
    station = s;
    if (s < 0) { audio_jukebox_stop(); return; }
    int pick[NSONGS], n = 0;
    for (int i = 0; i < NSONGS; i++) if (in_station(s, i) && i != cur_song) pick[n++] = i;
    if (n) audio_jukebox_play(pick[rand() % n]);
}
void audio_jukebox_next(void) {
    if (station >= 0) { audio_station_play(station); return; }
    if (NSONGS == 0) return;
    int n = shuffle ? (int)(rand() % NSONGS) : (cur_song + 1) % NSONGS;
    if (shuffle && n == cur_song) n = (n + 1) % NSONGS;
    audio_jukebox_play(n);
}
void audio_update(void) {
    if (dj_mode) { dj_pump(); if (cur_song < 0) return; }
    if (cur_song < 0) return;
    play_frames++;
    if (songs[cur_song].stream) { st_feed(); if (st_done) audio_jukebox_next(); return; }
    if (dj_mode) return;
    if (dk[0].laps > 0 && cur_song != 0) audio_jukebox_next();       // a song moves on when it has played once (THE DIPPER MAN, the title song, loops)
}

void audio_init(void) {
    SpuInit();
    spu_ok = 1;
    SpuSetCommonMasterVolume(master_v, master_v);
    music_silence();
    cd_ok = 0;
    song_base = spu_next;
    if (CdInit()) {
        cd_up = 1;
        // the voice clips: VOICES.BIN (u32 count, then {u32 offset, u32 size, u32 rate} per clip, then the ADPCM data) straight into
        // sound memory as it is, through the sequence buffer a piece at a time; each clip plays from where it landed
        CdlFILE vf;
        if (CdSearchFile(&vf, "\\VOICES.BIN;1")) {
            songs_loc = vf.pos;
            int secs = (int)((vf.size + 2047) / 2048), at = ALLOC_START, ok = 1;
            u32 hdr[1 + 3 * 32];
            for (int s = 0; s < secs && ok; s += SEQ_MAX / 2048) {
                int k = MIN(SEQ_MAX / 2048, secs - s);
                if (!cd_read((u32)s, k, seqbuf)) { ok = 0; break; }
                if (s == 0) memcpy(hdr, seqbuf, sizeof hdr);
                spu_write(at, seqbuf, k * 2048); at += k * 2048;
            }
            if (ok) {
                int n = (int)hdr[0];
                for (int i = 0; i < VOICE_N && i < n && i < 32; i++) { voice_addr[i] = ALLOC_START + (int)hdr[1 + i * 3]; voice_rate[i] = (int)hdr[3 + i * 3]; }
                spu_next = ALLOC_START + (int)((vf.size + 63) & ~63u); song_base = spu_next;   // every song's samples go after them (the biggest is SONG_SMP_MAX bytes)
            }
        }
        CdlFILE f;
        if (CdSearchFile(&f, "\\SONGS.BIN;1")) {
            songs_loc = f.pos;
            if (cd_read(0, 1, seqbuf)) {
                const u32 *ix = seqbuf;
                if (ix[0] == 0x474E5342 && (int)ix[1] == NSONGS) {
                    for (int i = 0; i < NSONGS; i++) { sidx[i].sector = ix[2 + i * 4]; sidx[i].seq_sectors = ix[3 + i * 4]; sidx[i].smp_sectors = ix[4 + i * 4]; sidx[i].smp_bytes = ix[5 + i * 4]; }
                    cd_ok = 1;
                }
            }
        }
    }
    // the sequencer's clock: timer 2 (CPU clock / 8) interrupts TICK_HZ times a second
    EnterCriticalSection();
    TIMER_CTRL(2) = 0x0258;                              // CLK/8, reset at the target, IRQ at the target, repeat
    TIMER_RELOAD(2) = (u16)((F_CPU / 8) / TICK_HZ);
    InterruptCallback(IRQ_TIMER2, &seq_tick);
    ExitCriticalSection();
}

