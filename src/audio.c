// audio.c - the voices and the jukebox, both on the SPU (the PS1 sound chip).
// The jukebox plays SEQUENCES: every song is its note events plus small instrument samples (tools/build_music.py runs the GBA game's
// own XM converter, so the notes, volumes and pans are the GBA version's). One song's samples sit in sound memory; a 480 Hz timer
// interrupt walks the rows and keys the notes on, so the chip does all the playing and the timing never depends on the frame rate.
#include "audio.h"
#include <psxspu.h>
#include <psxcd.h>
#include <hwregs_c.h>
#include "songs.inc"
#include "seqdec.h"     // GENERATED by tools/build_music.py: the song table (seconds, name, artist)


#define MUS_CH     16                  // music voices 0..15 (every song uses at most 16 channels)
#define CLIP_CH0   16                  // voice clips on 16..23
#define CLIP_N     8
#define MIXR       18157               // the rate the GBA converter's timing is counted in
#define TICK_HZ    480                 // the sequencer's timer
#define SEQ_MAX    (20 * 2048)         // the biggest song's sequence block, packed (tools/pack_songs.py: worthless_clouds, 17 sectors); the stream's FIFO

// ---- sound memory ----
#define ALLOC_START 0x1010
static int spu_next = ALLOC_START, song_base;
static int voice_addr[VOICE_N], voice_rate[VOICE_N];
static int next_clip = 0;
static int spu_ok;

static void spu_write(int addr, const void *data, int size) {
    SpuSetTransferMode(SPU_TRANSFER_BY_DMA);
    SpuSetTransferStartAddr(addr);
    SpuWrite((const u32 *)data, (size + 63) & ~63);
    SpuIsTransferCompleted(SPU_TRANSFER_WAIT);
}
static int upload_sample(const void *data, int size) {
    int addr = spu_next;
    spu_write(addr, data, size);
    spu_next = addr + ((size + 63) & ~63);
    return addr;
}

void audio_voice(int v) {
    if (!spu_ok || v < 0 || v >= VOICE_N || !voice_addr[v]) return;
    int ch = CLIP_CH0 + next_clip;
    SpuSetKey(0, 1 << ch);
    SPU_CH_FREQ(ch) = getSPUSampleRate(voice_rate[v]);
    SPU_CH_ADDR(ch) = getSPUAddr(voice_addr[v]);
    SPU_CH_VOL_L(ch) = 0x2fff;
    SPU_CH_VOL_R(ch) = 0x2fff;
    SPU_CH_ADSR1(ch) = 0x00ff;
    SPU_CH_ADSR2(ch) = 0x0000;
    SpuSetKey(1, 1 << ch);
    next_clip = (next_clip + 1) % CLIP_N;
}

// ---- the song file (SONGS.BIN): a one-sector index, then per song its sequence sectors and its sample sectors ----
static u32 seqbuf[SEQ_MAX / 4];
static CdlLOC songs_loc;
static int cd_ok;
static struct { u32 sector, seq_sectors, smp_sectors, smp_bytes; } sidx[NSONGS];

// ---- the sequencer (all of this is read inside the timer interrupt) ----
typedef struct {
    u32 magic, nord, loop, rowN, rfr, npat, ninst, nvt, ev_size, smp_size, seconds;
    u32 o_order, o_rows, o_patoff, o_vt, o_pitch, o_smpoff, o_bus, o_ev, pad;
} SeqHeader;
static volatile int sq_on;
static const SeqHeader *sq;
static const u8 *sq_order, *sq_bus, *sq_ev;
static const u16 *sq_rows, *sq_vt, *sq_pitch;
static const u32 *sq_patoff, *sq_smpoff;
static int sq_ord, sq_row;
static SeqDec sq_dec;                  // the notes, unpacked a row at a time
static const u8 *sq_body; static u32 sq_body_len;   // the part that loops
static u32 sq_acc, sq_rowlen;          // the row clock: +MIXR*256 per tick; a row is (rowN*256 + rfr) * TICK_HZ
static volatile int sq_laps;
static int music_vol = 320;
void audio_music_level(int l) { static const short lv[4] = { 0, 110, 210, 320 }; music_vol = lv[l & 3]; }   // OFF, LOW, MEDIUM, FULL (from the next note on)
static int music_vol_unused;            // 256 = the GBA level (a touch louder: the SPU has the headroom)

static void seq_row(void) {
    int n = seqdec_row(&sq_dec);
    u32 on = 0;
    while (n--) {
        u32 w = (u32)seqdec_byte(&sq_dec); w |= (u32)seqdec_byte(&sq_dec) << 8; w |= (u32)seqdec_byte(&sq_dec) << 16;
        u32 t = sq_vt[(w & 255) | ((w >> 22) << 8)];
        int ch = t & 15, in = (t >> 4) & 31, bus = (t >> 9) & 7, nt = (w >> 8) & 127, vol = (w >> 15) & 127, rel = t >> 12;
        if (nt == 127) { SPU_KEY_OFF1 = (u16)(1u << ch); continue; }   // a key off (the songs made from renders: tools/build_midi_songs.py): the note fades on its release
        if (bus > 6) bus = 3;
        u32 so = sq_smpoff[in];
        if (so == 0xffffffff || nt >= 96) continue;
        int vl = (vol * sq_bus[bus] * music_vol) >> 9, vr = (vol * sq_bus[7 + bus] * music_vol) >> 9;   // the GBA's level: vol x bus / 2
        SPU_CH_VOL_L(ch) = vl > 0x3fff ? 0x3fff : vl;
        SPU_CH_VOL_R(ch) = vr > 0x3fff ? 0x3fff : vr;
        SPU_CH_FREQ(ch) = sq_pitch[in * 96 + nt];
        SPU_CH_ADDR(ch) = getSPUAddr(song_base + (int)so);
        SPU_CH_ADSR1(ch) = 0x00ff;                       // instant attack, full sustain: the sample plays as it is (one-shot)
        { static const u16 relTab[4] = { 0x0005, 0x000C, 0x000D, 0x000E };   // the release when a note is cut: short (the tracker songs), or 0.2, 0.4, 0.7 s (a held sound let go)
          SPU_CH_ADSR2(ch) = relTab[rel & 3]; }
        on |= 1u << ch;
    }
    if (on) SPU_KEY_ON1 = (u16)on;
    if (++sq_row >= sq_rows[sq_order[sq_ord]]) {
        sq_row = 0;
        if (++sq_ord >= (int)sq->nord) { sq_ord = (int)sq->loop; sq_laps++; seqdec_start(&sq_dec, sq_body, sq_body_len); }
        else if (sq_ord == (int)sq->loop) seqdec_start(&sq_dec, sq_body, sq_body_len);   // (the intro played: the part that loops)
    }
}
extern void prof_sample(void);
static void seq_tick(void) {
    prof_sample();
    if (!sq_on) return;
    sq_acc += MIXR * 256;
    while (sq_acc >= sq_rowlen) { sq_acc -= sq_rowlen; seq_row(); }
}
static void music_silence(void) {
    sq_on = 0;
    SPU_KEY_OFF1 = 0xffff;
    for (int ch = 0; ch < MUS_CH; ch++) { SPU_CH_VOL_L(ch) = 0; SPU_CH_VOL_R(ch) = 0; }
}

// ---- REVERB: the sound chip's own, one preset per song (songs.inc fx) ----
// The delays are the hardware docs' ROOM layout (a 0x26C0-byte work area at the top of sound memory); the presets change how
// loud the reverb is, how dark (vIIR) and how long it rings (vWALL, vCOMB) - DRY, ROOM, WARM, BIG SPACE, CAVE.
#define REV_SIZE 0x26C0
#define REV_ADDR (0x80000 - REV_SIZE)
static const u16 revRoom[32] = { 0x007D, 0x005B, 0x6D80, 0x54B8, 0xBED0, 0x0000, 0x0000, 0xBA80, 0x5800, 0x5300, 0x04D6, 0x0333, 0x03F0, 0x0227,
                                 0x0374, 0x01EF, 0x0334, 0x01B5, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x01B4, 0x0136,
                                 0x00B8, 0x005C, 0x8000, 0x8000 };
static const struct { u16 send, iir, wall, comb1, comb2; } revFx[5] = {
    { 0x0000, 0x6D80, 0xBA80, 0x54B8, 0xBED0 },   // DRY
    { 0x1600, 0x6D80, 0xBA80, 0x54B8, 0xBED0 },   // ROOM
    { 0x2000, 0x4E00, 0xB000, 0x5C00, 0xBA00 },   // WARM (darker, a little longer)
    { 0x2A00, 0x6D80, 0xA400, 0x6600, 0xB400 },   // BIG SPACE
    { 0x3000, 0x5800, 0x9C00, 0x7000, 0xAE00 },   // CAVE (long and dark)
};
static int rev_ready;
static void reverb_set(int fx) {
    if (!rev_ready) {   // the work area starts silent
        static u32 zero[256];
        for (int a = REV_ADDR; a < 0x80000; a += sizeof zero) spu_write(a, zero, sizeof zero);
        SPU_REVERB_ADDR = getSPUAddr(REV_ADDR);
        rev_ready = 1;
    }
    fx %= 5;
    for (int i = 0; i < 32; i++) {
        u16 v = revRoom[i];
        if (i == 2) v = revFx[fx].iir; if (i == 7) v = revFx[fx].wall; if (i == 3) v = revFx[fx].comb1; if (i == 4) v = revFx[fx].comb2;
        _MMIO16((IOBASE | 0x1dc0) + 2 * i) = v;
    }
    SPU_REVERB_VOL_L = revFx[fx].send; SPU_REVERB_VOL_R = revFx[fx].send;
    SPU_REVERB_ON1 = revFx[fx].send ? 0xffff : 0;     // the music voices (0..15) feed it; the voice clips stay dry
    SPU_CTRL |= 0x80;
}

