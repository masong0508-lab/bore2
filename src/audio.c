// audio.c - the voices and the jukebox, both on the SPU (the PS1 sound chip).
// The jukebox plays SEQUENCES: every song is its note events plus small instrument samples (tools/build_music.py runs the GBA game's
// own XM converter, so the notes, volumes and pans are the GBA version's). One song's samples sit in sound memory; a 480 Hz timer
// interrupt walks the rows and keys the notes on, so the chip does all the playing and the timing never depends on the frame rate.
#include "audio.h"
#include <psxspu.h>
#include <psxcd.h>
#include <hwregs_c.h>
#include "songs.inc"
#include "seqdec.h"     // GENERATED by tools/build_music.py: the song table (seconds, name, artist)


#define MUS_CH     16                  // music voices 0..15 (every song uses at most 16 channels)
#define CLIP_CH0   16                  // voice clips on 16..23
#define CLIP_N     8
#define MIXR       18157               // the rate the GBA converter's timing is counted in
#define TICK_HZ    480                 // the sequencer's timer
#define SEQ_MAX    (20 * 2048)         // the biggest song's sequence block, packed (tools/pack_songs.py: worthless_clouds, 17 sectors); the stream's FIFO

// ---- sound memory ----
#define ALLOC_START 0x1010
static int spu_next = ALLOC_START, song_base;
static int voice_addr[VOICE_N], voice_rate[VOICE_N];
static int next_clip = 0;
static int spu_ok;

static void spu_write(int addr, const void *data, int size) {
    SpuSetTransferMode(SPU_TRANSFER_BY_DMA);
    SpuSetTransferStartAddr(addr);
    SpuWrite((const u32 *)data, (size + 63) & ~63);
    SpuIsTransferCompleted(SPU_TRANSFER_WAIT);
}
static int upload_sample(const void *data, int size) {
    int addr = spu_next;
    spu_write(addr, data, size);
    spu_next = addr + ((size + 63) & ~63);
    return addr;
}

// the volume curve of the GBA game's options (0..10: a gentle ear-shaped climb to 256 = full)
static const short volTab[11] = { 0, 8, 17, 28, 42, 60, 84, 114, 150, 198, 256 };
static int sfx_gain = 256, master_v = 0x3fff;

void audio_voice(int v) {
    if (!spu_ok || v < 0 || v >= VOICE_N || !voice_addr[v]) return;
    int ch = CLIP_CH0 + next_clip;
    SpuSetKey(0, 1 << ch);
    SPU_CH_FREQ(ch) = getSPUSampleRate(voice_rate[v]);
    SPU_CH_ADDR(ch) = getSPUAddr(voice_addr[v]);
    SPU_CH_VOL_L(ch) = 0x2fff * sfx_gain >> 8;
    SPU_CH_VOL_R(ch) = 0x2fff * sfx_gain >> 8;
    SPU_CH_ADSR1(ch) = 0x00ff;
    SPU_CH_ADSR2(ch) = 0x0000;
    SpuSetKey(1, 1 << ch);
    next_clip = (next_clip + 1) % CLIP_N;
}

// ---- the song file (SONGS.BIN): a one-sector index, then per song its sequence sectors and its sample sectors ----
static u32 seqbuf[(SEQ_MAX + 4096) / 4];   // (the sequence block, or two for the DJ; at its end the decks' unpacking windows)
#define SEQ_RING(d) ((u8 *)seqbuf + 36864 + (d) * 4096)
static CdlLOC songs_loc;
static int cd_ok, cd_up;   // (cd_up: the drive answered at start-up)
static struct { u32 sector, seq_sectors, smp_sectors, smp_bytes; } sidx[NSONGS];

// ---- the sequencer (all of this is read inside the timer interrupt) ----
// Two DECKS: the jukebox plays on deck 0 alone (every track on the voice of its own channel); the DJ (dj_*, below) runs both, the notes of
// either taking whichever voice has been quiet longest, so two songs can sound at once and one fade into the other.
typedef struct {
    u32 magic, nord, loop, rowN, rfr, npat, ninst, nvt, ev_size, smp_size, seconds;
    u32 o_order, o_rows, o_patoff, o_vt, o_pitch, o_smpoff, o_bus, o_ev, pad;
} SeqHeader;
typedef struct {
    volatile int on;
    const SeqHeader *sq;
    const u8 *order, *bus, *ev, *body;
    const u16 *rows, *vt, *pitch;
    const u32 *patoff, *smpoff;
    int ord, row, loop_ord, end_ord, base;     // where it is; the order it loops to and the one it ends on (an excerpt); its samples in sound memory
    SeqDec dec; u32 body_len;
    u32 acc, rowlen, rowlen0;                  // the row clock: +MIXR*256 per tick; a row is (rowN*256 + rfr) * TICK_HZ (rowlen0 at the song's own tempo)
    volatile int laps, gain, tempo, pmul, mute, pending, cue_row, act, bars;   // laps; 0..256 fade; 8.8 tempo; 8.8 pitch (a scratch); channels muted; waiting for the other deck's order; ..; notes lately; orders played
} Deck;
static Deck dk[2];
// ---- THE BAND (SUPERSTAR): the jukebox's deck 0, with every instrument's part played at its player's skill ----
// A note names its instrument, and tools/band_roles.py says which skill plays each instrument (1 drums, 2 guitar/bass, 3 keys, 4 voice, 5 stage
// effects). band_q[role] is how well that part is played, 0..256: a part played badly drops notes, goes sour and thin; played well it is
// full, and at the top it shines. The ear is the only judge; band_n / band_miss count what was played and what was dropped.
static volatile int band_on; static u8 band_role[32]; static int band_q[6] = { 256, 256, 256, 256, 256, 256 };
volatile int band_n[6], band_miss[6]; static u32 band_seed = 0x9e3779b9u;
static inline u32 band_rng(void) { band_seed ^= band_seed << 13; band_seed ^= band_seed >> 17; band_seed ^= band_seed << 5; return band_seed; }
void audio_band_set(const unsigned char *role32, const int *q6) { for (int i = 0; i < 32; i++) band_role[i] = role32 ? role32[i] : 0; for (int i = 0; i < 6; i++) band_q[i] = q6 ? q6[i] : 256; for (int i = 0; i < 6; i++) band_n[i] = band_miss[i] = 0; band_on = role32 != 0; }
void audio_band_quality(int role, int q) { if (role >= 0 && role < 6) band_q[role] = q < 0 ? 0 : q > 256 ? 256 : q; }
static volatile int dj_mode;                    // 1: the DJ has both decks (voices are shared out as notes come)
static u32 vtime[MUS_CH]; static int vdeck[MUS_CH], vtch[MUS_CH], vbl[MUS_CH], vbr[MUS_CH], vfreq[MUS_CH];
static u32 vclock;
static int music_vol = 320;
void audio_music_level(int l) { static const short lv[4] = { 0, 110, 210, 320 }; music_vol = lv[l & 3]; }   // OFF, LOW, MEDIUM, FULL (from the next note on)
void audio_volumes(int master, int music, int sfx) {   // OPTIONS > AUDIO: three sliders, 0..10 each
    master = master < 0 ? 0 : master > 10 ? 10 : master; music = music < 0 ? 0 : music > 10 ? 10 : music; sfx = sfx < 0 ? 0 : sfx > 10 ? 10 : sfx;
    master_v = 0x3fff * volTab[master] >> 8; music_vol = 320 * volTab[music] >> 8; sfx_gain = volTab[sfx];
    if (spu_ok) SpuSetCommonMasterVolume(master_v, master_v);
}
static int music_vol_unused;            // 256 = the GBA level (a touch louder: the SPU has the headroom)
static volatile int dj_wash;            // the DJ's echo: reverb added on top

static int voice_for(int di, int tch) {
    if (!dj_mode) return tch;
    for (int v = 0; v < MUS_CH; v++) if (vdeck[v] == di + 1 && vtch[v] == tch) { vtime[v] = ++vclock; return v; }   // (its own voice again)
    int best = 0; u32 old = 0xffffffffu;
    for (int v = 0; v < MUS_CH; v++) if (vtime[v] < old) { old = vtime[v]; best = v; }
    vdeck[best] = di + 1; vtch[best] = tch; vtime[best] = ++vclock; return best;
}
static void deck_row(int di) {
    Deck *d = &dk[di];
    int n = seqdec_row(&d->dec);
    u32 on = 0;
    while (n--) {
        u32 w = (u32)seqdec_byte(&d->dec); w |= (u32)seqdec_byte(&d->dec) << 8; w |= (u32)seqdec_byte(&d->dec) << 16;
        u32 t = d->vt[(w & 255) | ((w >> 22) << 8)];
        int tch = t & 15, in = (t >> 4) & 31, bus = (t >> 9) & 7, nt = (w >> 8) & 127, vol = (w >> 15) & 127, rel = t >> 12;
        if (nt == 127) { if (!dj_mode) SPU_KEY_OFF1 = (u16)(1u << tch); else for (int v = 0; v < MUS_CH; v++) if (vdeck[v] == di + 1 && vtch[v] == tch) SPU_KEY_OFF1 = (u16)(1u << v); continue; }   // a key off (the songs made from renders): the note fades on its release
        if (bus > 6) bus = 3;
        u32 so = d->smpoff[in];
        if (so == 0xffffffff || nt >= 96) continue;
        d->act++;
        if (d->mute & (1 << tch)) continue;                           // (a channel the DJ has killed)
        int bdt = 0, bvs = 256, harm = 0; u32 hh = 0;
        if (band_on && !dj_mode) {
            int r = band_role[in];
            if (r) {
                band_n[r]++;
                if (r != 5) {
                    int q = band_q[r]; u32 h = band_rng();
                    int pd = (((256 - q) * (256 - q)) >> 8) * (r == 1 ? 100 : 150) >> 8;   // the chance (of 256) the note is not played
                    if ((int)(h & 255) < pd) { band_miss[r]++; continue; }
                    if (r != 1) bdt = ((int)((h >> 8) & 255) - 128) * (256 - q) >> 7;         // a sour note: up to a semitone out (+-6 % of the pitch)
                    if (q >= 240 && r >= 2 && r <= 4 && vol > 24) { hh = h >> 20; if ((hh & 3) == 0) harm = r == 3 ? 2 * 4096 : 3 * 2048; }   // a master adds a fifth (or, on keys, an octave) now and then
                    bvs = 154 + ((q * 102) >> 8) + (q >= 240 ? 26 : 0) + ((int)((h >> 16) & 15) - 8) * (256 - q) / 256;   // thin when poor, full when good
                }
            }
        }
        int ch = voice_for(di, tch);
        int vl = (vol * d->bus[bus] * music_vol) >> 9, vr = (vol * d->bus[7 + bus] * music_vol) >> 9;
        if (bvs != 256) { vl = vl * bvs >> 8; vr = vr * bvs >> 8; }   // the GBA's level: vol x bus / 2
        if (vl > 0x3fff) vl = 0x3fff; if (vr > 0x3fff) vr = 0x3fff;
        vbl[ch] = vl; vbr[ch] = vr; vfreq[ch] = d->pitch[in * 96 + nt];
        if (dj_mode) { vl = vl * d->gain >> 8; vr = vr * d->gain >> 8; }
        SPU_CH_VOL_L(ch) = vl;
        SPU_CH_VOL_R(ch) = vr;
        SPU_CH_FREQ(ch) = dj_mode ? (vfreq[ch] * d->pmul >> 8) : bdt ? vfreq[ch] * (4096 + bdt) >> 12 : vfreq[ch];
        SPU_CH_ADDR(ch) = getSPUAddr(d->base + (int)so);
        SPU_CH_ADSR1(ch) = 0x00ff;                       // instant attack, full sustain: the sample plays as it is (one-shot)
        { static const u16 relTab[4] = { 0x0005, 0x000C, 0x000D, 0x000E };   // the release when a note is cut: short (the tracker songs), or 0.2, 0.4, 0.7 s (a held sound let go)
          SPU_CH_ADSR2(ch) = relTab[rel & 3]; }
        on |= 1u << ch;
        if (harm) {                                      // the harmony: a quieter copy a fifth/octave up, on a spare clip voice, left to fade
            int hc = CLIP_CH0 + CLIP_N - 1 - (hh >> 2 & 1), hv = vl * 2 / 5, hr = vr * 2 / 5;
            SpuSetKey(0, 1 << hc);
            SPU_CH_FREQ(hc) = (vfreq[ch] * harm) >> 12 > 0x3fff ? 0x3fff : (vfreq[ch] * harm) >> 12;
            SPU_CH_ADDR(hc) = getSPUAddr(d->base + (int)so);
            SPU_CH_VOL_L(hc) = hv; SPU_CH_VOL_R(hc) = hr;
            SPU_CH_ADSR1(hc) = 0x00ff; SPU_CH_ADSR2(hc) = 0xCC00;
            SpuSetKey(1, 1 << hc);
        }
    }
    if (on) SPU_KEY_ON1 = (u16)on;
    if (++d->row >= d->rows[d->order[d->ord]]) {
        d->row = 0; d->bars++;
        if (++d->ord >= d->end_ord) { d->ord = d->loop_ord; d->laps++; seqdec_start(&d->dec, d->body, d->body_len); }
        else if (d->ord == d->loop_ord) seqdec_start(&d->dec, d->body, d->body_len);   // (the intro played: the part that loops)
    }
}
extern void prof_sample(void);
static void seq_tick(void) {
    prof_sample();
    for (int di = 0; di < 2; di++) {
        Deck *d = &dk[di];
        if (!d->on) continue;
        d->acc += MIXR * 256;
        while (d->acc >= d->rowlen) { d->acc -= d->rowlen; deck_row(di);
            if (dj_mode) { Deck *o = &dk[di ^ 1]; if (o->pending && !o->on && d->row == o->cue_row) { o->pending = 0; o->acc = o->rowlen; o->on = 1; } }   // the other deck was waiting for this deck's order (or a row of it: a late cue)
        }
    }
}
static void music_silence(void) {
    band_on = 0;
    dk[0].on = dk[1].on = 0; dk[0].pending = dk[1].pending = 0; dj_mode = 0;
    SPU_KEY_OFF1 = 0xffff;
    for (int ch = 0; ch < MUS_CH; ch++) { SPU_CH_VOL_L(ch) = 0; SPU_CH_VOL_R(ch) = 0; vdeck[ch] = 0; vtime[ch] = 0; }
}

// ---- REVERB: the sound chip's own, one preset per song (songs.inc fx) ----
// The delays are the hardware docs' ROOM layout (a 0x26C0-byte work area at the top of sound memory); the presets change how
// loud the reverb is, how dark (vIIR) and how long it rings (vWALL, vCOMB) - DRY, ROOM, WARM, BIG SPACE, CAVE.
#define REV_SIZE 0x26C0
#define REV_ADDR (0x80000 - REV_SIZE)
static const u16 revRoom[32] = { 0x007D, 0x005B, 0x6D80, 0x54B8, 0xBED0, 0x0000, 0x0000, 0xBA80, 0x5800, 0x5300, 0x04D6, 0x0333, 0x03F0, 0x0227,
                                 0x0374, 0x01EF, 0x0334, 0x01B5, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x0000, 0x01B4, 0x0136,
                                 0x00B8, 0x005C, 0x8000, 0x8000 };
static const struct { u16 send, iir, wall, comb1, comb2; } revFx[5] = {
    { 0x0000, 0x6D80, 0xBA80, 0x54B8, 0xBED0 },   // DRY
    { 0x1600, 0x6D80, 0xBA80, 0x54B8, 0xBED0 },   // ROOM
    { 0x2000, 0x4E00, 0xB000, 0x5C00, 0xBA00 },   // WARM (darker, a little longer)
    { 0x2A00, 0x6D80, 0xA400, 0x6600, 0xB400 },   // BIG SPACE
    { 0x3000, 0x5800, 0x9C00, 0x7000, 0xAE00 },   // CAVE (long and dark)
};
static int rev_ready;
static void reverb_set(int fx) {
    if (!rev_ready) {   // the work area starts silent
        static u32 zero[256];
        for (int a = REV_ADDR; a < 0x80000; a += sizeof zero) spu_write(a, zero, sizeof zero);
        SPU_REVERB_ADDR = getSPUAddr(REV_ADDR);
        rev_ready = 1;
    }
    fx %= 5;
    for (int i = 0; i < 32; i++) {
        u16 v = revRoom[i];
        if (i == 2) v = revFx[fx].iir; if (i == 7) v = revFx[fx].wall; if (i == 3) v = revFx[fx].comb1; if (i == 4) v = revFx[fx].comb2;
        _MMIO16((IOBASE | 0x1dc0) + 2 * i) = v;
    }
    SPU_REVERB_VOL_L = revFx[fx].send; SPU_REVERB_VOL_R = revFx[fx].send;
    SPU_REVERB_ON1 = revFx[fx].send ? 0xffff : 0;     // the music voices (0..15) feed it; the voice clips stay dry
    SPU_CTRL |= 0x80;
}

static int deck_setup(Deck *d, const u8 *b, int base, int dj) {   // a song's sequence block (BSQ2: packed by tools/pack_songs.py) ready on a deck
    const SeqHeader *sq = (const SeqHeader *)b;
    if (sq->magic != 0x32515342) return 0;
    d->on = 0; d->pending = 0; d->sq = sq; d->dec.ring = SEQ_RING(d == &dk[1]);
    d->order = b + sq->o_order; d->rows = (const u16 *)(b + sq->o_rows); d->patoff = (const u32 *)(b + sq->o_patoff);
    d->vt = (const u16 *)(b + sq->o_vt); d->pitch = (const u16 *)(b + sq->o_pitch); d->smpoff = (const u32 *)(b + sq->o_smpoff);
    d->bus = b + sq->o_bus; d->ev = b + sq->o_ev;
    { const u32 *x = (const u32 *)(b + sq->pad); d->body = b + x[1]; d->body_len = x[2];   // the intro's and the loop's packed notes
      if (sq->loop && !dj) seqdec_start(&d->dec, d->ev, x[0]); else seqdec_start(&d->dec, d->body, d->body_len); }
    d->ord = dj ? (int)sq->loop : 0; d->row = 0; d->laps = 0; d->bars = 0; d->act = 0;
    d->loop_ord = (int)sq->loop; d->end_ord = (int)sq->nord; d->base = base;
    d->rowlen0 = (sq->rowN * 256 + sq->rfr) * TICK_HZ; d->tempo = 256; d->rowlen = d->rowlen0;
    d->acc = d->rowlen - MIXR * 256;                     // the first row sounds on the first tick
    d->gain = 256; d->pmul = 256; d->mute = 0; d->cue_row = 0;
    return 1;
}
