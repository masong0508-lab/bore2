#!/usr/bin/env python3
# mkitems.py OUT.h: the item letters' properties (blocking, flat, turned, footprint) read from src/items.c and its .inc packs, for the host lot simulator.
import re, glob, os, sys
src = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..', 'src')
txt = open(os.path.join(src, 'items.c')).read()
for f in sorted(glob.glob(os.path.join(src, 'items_*.inc'))):
    txt += '\n' + open(f).read()
chs = {}
for f in glob.glob(os.path.join(src, '*.h')) + glob.glob(os.path.join(src, '*.inc')):
    for m in re.finditer(r'#define\s+(CH_\w+)\s+\(\(char\)(0x[0-9A-Fa-f]+)\)', open(f).read()):
        chs[m.group(1)] = int(m.group(2), 16)
FL = {'F_ROT': 1, 'F_ALONG': 2, 'F_FLAT': 4, 'F_HIGH': 8, 'F_L2': 16, 'F_W2': 32, 'F_KERB': 64}
def ch(s):
    s = s.strip()
    if s in chs: return chs[s]
    m = re.match(r'\(char\)(0x[0-9A-Fa-f]+)$', s)
    if m: return int(m.group(1), 16)
    m = re.match(r"'(.*)'$", s)
    v = m.group(1)
    if v.startswith('\\x'): return int(v[2:], 16)
    if v == "\\\\": return 92
    if v == "\\'": return 39
    return ord(v)
rows = {}
pat = re.compile(r"\{\s*('(?:\\x[0-9A-Fa-f]{2}|\\.|[^'\\])'|CH_[A-Z0-9]+|\(char\)0x[0-9A-Fa-f]+)\s*,\s*\"([^\"]*)\"\s*,\s*(\w+)\s*,\s*(\d+)\s*,\s*(\w+)\s*,\s*(\d+)\s*,\s*([^,]+),\s*(\d+)\s*\}")
for m in pat.finditer(txt):
    c = ch(m.group(1)); fl = 0
    for t in m.group(7).split('|'):
        t = t.strip()
        if t in FL: fl |= FL[t]
    rows.setdefault(c, (fl, m.group(2)))     # (items.c def_of: the first def of a letter wins)
# the same aliases items.c's def_of makes: a kicker turned
rows[ord('2')] = rows[ord('4')] = rows[ord('1')]
out = ['// GENERATED by mkitems.py: letter -> flags (1 turned, 2 along, 4 flat, 8 high, 16 two long, 32 two wide, 64 kerb pole), name', 'static const struct { unsigned char c, f; const char *n; } itab[] = {']
for c in sorted(rows): out.append('  { %d, %d, "%s" },' % (c, rows[c][0], rows[c][1]))
out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print(len(rows), 'items')
