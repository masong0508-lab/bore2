#!/usr/bin/env python3
"""Hair textures for BORE 2 (greyscale 15-bit, modulated by the hair colour in the GTE):
  hair_side 16x32: rows 0..15 the top layer (a sheen band under the crown), rows 16..31 plain strands (tile vertically)
  hair_crown 16x16: the top of the head: a whorl of strands
  hair_tips 16x16: the last layer of a hanging cut: strands that end in points (0 = see-through)
  hair_fringe 16x16: bangs over the forehead (0 = see-through)
  hair_curl 16x16: afro / curls: a bumpy pile
Written to src/hairtex.inc"""
import math, random, sys
random.seed(7)
def g(v):   # grey 0..1 -> 15-bit
    v = max(0.0, min(1.0, v)); c = int(v * 31 + 0.5)
    return (c | (c << 5) | (c << 10)) or 0x8000
def strand_cols(n, base=0.48, spread=0.16):
    return [base + random.uniform(-spread, spread) for _ in range(n)]

out = {}
# ---- side: 16 wide, 32 tall ----
cols = strand_cols(16)
side = []
for y in range(32):
    row = []
    for x in range(16):
        v = cols[x] + random.uniform(-0.04, 0.04)
        # a second, finer strand pattern
        v += 0.05 * math.sin(x * 2.1 + (y % 16) * 0.15)
        if y < 16:
            # the sheen band under the crown, brightest on row 4
            v += 0.42 * math.exp(-((y - 4) / 2.4) ** 2) * (0.7 + 0.3 * cols[x])
            if y == 0: v += 0.06
        row.append(g(v))
    side.append(row)
out['hair_side'] = (16, 32, side)
# ---- crown: a whorl ----
crown = []
cx, cy = 9.5, 7.0
for y in range(16):
    row = []
    for x in range(16):
        a = math.atan2(y - cy, x - cx); r = math.hypot(x - cx, y - cy)
        v = 0.5 + 0.17 * math.sin(a * 9 + r * 0.9) + 0.06 * math.sin(a * 23) + random.uniform(-0.04, 0.04)
        v += 0.12 * math.exp(-((r - 2.5) / 2.5) ** 2)      # a soft highlight ring round the whorl
        row.append(g(v))
    crown.append(row)
out['hair_crown'] = (16, 16, crown)
# ---- tips: strands ending in points ----
ends = [random.randint(7, 15) for _ in range(16)]
tips = []
for y in range(16):
    row = []
    for x in range(16):
        v = cols[x] + random.uniform(-0.04, 0.04) - y * 0.012
        e = ends[x]
        if y > e: row.append(0)                          # see-through
        else:
            if y >= e - 1: v -= 0.12                     # darker right at the point
            row.append(g(v))
    tips.append(row)
out['hair_tips'] = (16, 16, tips)
# ---- fringe: bangs, longer in the middle, parted a little ----
fr = []
fends = [int(5 + 7 * math.sin(math.pi * (x + 0.5) / 16) + random.uniform(-1.5, 1.5)) for x in range(16)]
for y in range(16):
    row = []
    for x in range(16):
        v = cols[(x * 3) % 16] + 0.05 + random.uniform(-0.04, 0.04) - y * 0.01
        if y <= 1: v += 0.08
        if x in (7, 8) and y > 3: v -= 0.1                # a hint of a parting
        if y > fends[x] or (x in (7, 8) and y > 6): row.append(0)
        else: row.append(g(v))
    fr.append(row)
out['hair_fringe'] = (16, 16, fr)
# ---- curls: bumps ----
curl = []
bumps = [(random.uniform(0, 16), random.uniform(0, 16), random.uniform(1.6, 2.6)) for _ in range(14)]
for y in range(16):
    row = []
    for x in range(16):
        v = 0.42
        for bx, by, br in bumps:
            for ox in (-16, 0, 16):
                for oy in (-16, 0, 16):
                    d = math.hypot(x - bx + ox, y - by + oy)
                    if d < br:
                        h = math.sqrt(max(0.0, 1 - (d / br) ** 2))
                        # lit from the top-left
                        v = max(v, 0.42 + 0.3 * h + 0.14 * ((bx - ox - x) * 0.3 + (by - oy - y) * 0.5) / br * h)
        row.append(g(v + random.uniform(-0.03, 0.03)))
    curl.append(row)
out['hair_curl'] = (16, 16, curl)

with open(sys.argv[1] if len(sys.argv) > 1 else 'src/hairtex.inc', 'w') as w:
    w.write('// GENERATED by tools/make_hairtex.py: the hair textures (grey, the hair colour modulates them)\n')
    for name, (wd, ht, rows) in out.items():
        w.write('static const u16 %s[%d * %d] = {\n' % (name, wd, ht))
        for r in rows: w.write('    ' + ','.join('0x%04x' % v for v in r) + ',\n')
        w.write('};\n')
print('ok')
