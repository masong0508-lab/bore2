# Turns docs/bore2_logo.png into rectangle lists (x,y,w,h,rgb555) for the title screens.
import sys
from PIL import Image
import numpy as np
def rects(w,h,ncol=14):
    im=Image.open('docs/bore2_logo_1x.png').convert('RGBA')
    assert im.size==(w,h)
    a=np.array(im); alpha=a[:,:,3]
    q=Image.fromarray(a[:,:,:3]).quantize(ncol,dither=Image.Dither.NONE).convert('RGB'); c=np.array(q)
    c5=(c>>3).astype(int); used=np.zeros((h,w),bool); out=[]
    for y in range(h):
        for x in range(w):
            if used[y,x] or alpha[y,x]<128: continue
            col=tuple(c5[y,x]); x2=x
            while x2+1<w and not used[y,x2+1] and alpha[y,x2+1]>=128 and tuple(c5[y,x2+1])==col: x2+=1
            y2=y
            while y2+1<h and all((not used[y2+1,xx]) and alpha[y2+1,xx]>=128 and tuple(c5[y2+1,xx])==col for xx in range(x,x2+1)): y2+=1
            used[y:y2+1,x:x2+1]=True
            out.append((x,y,x2-x+1,y2-y+1,col[0]|col[1]<<5|col[2]<<10))
    return out
def emit(name,w,h,path):
    r=rects(w,h); pal=sorted(set(t[4] for t in r)); idx={c:i for i,c in enumerate(pal)}
    with open(path,'w') as f:
        f.write(f"// generated by tools/make_logo.py: the BORE 2 logo as {len(r)} rectangles on a {w}x{h} grid, {len(pal)} colours\n#define {name}_W {w}\n#define {name}_H {h}\n#define {name}_N {len(r)}\n")
        f.write(f"static const unsigned short {name}_P[{len(pal)}] = {{"+",".join(map(str,pal))+"};\n")
        f.write(f"static const struct {{ unsigned char x, y, w, h, c; }} {name}_R[{len(r)}] = {{\n")
        f.write(",".join("{%d,%d,%d,%d,%d}"%(t[0],t[1],t[2],t[3],idx[t[4]]) for t in r)+"\n};\n")
    print(path,len(r),len(pal))
emit('LOGO',149,87,'src/logo_rects.h')
