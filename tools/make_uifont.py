#!/usr/bin/env python3
# make_uifont.py <fonttex.inc> <out.inc> [scale]: a smaller, smooth font for the menus and the HUD, made from BORE's medium font
# by shrinking each glyph with area averaging (so its edges stay soft instead of dropping pixels). The result is a 128-wide
# texture sheet in the same layout as the others (font.c's size 3).
import re, sys, math
src = open(sys.argv[1]).read(); out = sys.argv[2]; S = float(sys.argv[3]) if len(sys.argv) > 3 else 0.68
def define(n): return int(re.search(r'#define %s (\d+)' % n, src).group(1))
H, LINE, SPACE, TOP, SW = define('FONT_M_H'), define('FONT_M_LINE'), define('FONT_M_SPACE'), define('FONT_M_TOP'), define('FONT_SHEET_W')
gl = [tuple(map(int, g)) for g in re.findall(r'\{(\d+),(\d+),(\d+),(\d+)\}', re.search(r'font_m_glyph\[94\]\[4\] = \{(.*?)\};', src, re.S).group(1))]
nib = [int(v) for v in re.findall(r'\d+', re.search(r'font_m_a\[128 \* 126 / 2\] = \{[^\n]*\n(.*?)\};', src, re.S).group(1))]
px = [31 if a >= 8 else a * 31 // 8 for b in nib for a in (b & 15, b >> 4)]   # (the coverage as a grey 0..31)
assert len(gl) == 94 and len(px) == SW * H
def val(x, y): return px[y * SW + x] & 31          # (grey: one channel is enough)
NL = max(1, round(LINE * S))
glyphs, cells = [], []
for (gx, gy, gw, adv) in gl:
    nw = max(1, math.ceil(gw * S)) if gw else 0
    cell = [[0] * nw for _ in range(NL)]
    for oy in range(NL):
        for ox in range(nw):
            # the source box this output pixel covers, and how much of each source pixel falls inside it
            x0, x1, y0, y1 = ox / S, (ox + 1) / S, oy / S, (oy + 1) / S
            acc = area = 0.0
            for sy in range(int(y0), min(LINE, math.ceil(y1))):
                fy = min(y1, sy + 1) - max(y0, sy)
                for sx in range(int(x0), min(gw, math.ceil(x1))):
                    fx = min(x1, sx + 1) - max(x0, sx)
                    a = fx * fy; acc += val(gx + sx, gy + sy) * a; area += a
            v = acc / (1 / S / S) if area else 0
            v = min(31, int(round(min(31.0, v * 1.15))))   # (a touch bolder: small type reads better a little heavy)
            cell[oy][ox] = v
    cells.append(cell); glyphs.append([nw, max(1, round(adv * S)) if gw or adv else 0])
# pack into a 128-wide sheet
sheet_rows, x, y, rowh = [], 0, 0, NL + 1
pos = []
for c in cells:
    w = len(c[0]) if c and c[0] else 0
    if x + w + 1 > SW: x = 0; y += rowh
    pos.append((x, y)); x += w + 1
SH = y + rowh
sheet = [0] * (SW * SH)
for (cx, cy), c in zip(pos, cells):
    for yy, row in enumerate(c):
        for xx, v in enumerate(row):
            if v: sheet[(cy + yy) * SW + cx + xx] = v   # (a grey 0..31: font.c makes it a blending texel, added or taken away)
with open(out, 'w') as f:
    f.write('// GENERATED by tools/make_uifont.py from the medium font (fonttex.inc), shrunk %.2fx with area averaging\n' % S)
    f.write('#define FONT_U_H %d\n#define FONT_U_LINE %d\n#define FONT_U_SPACE %d\n#define FONT_U_TOP %d\n' % (SH, NL, max(2, round(SPACE * S)), round(TOP * S)))
    f.write('static const u8 font_u_glyph[94][4] = { %s };\n' % ', '.join('{%d,%d,%d,%d}' % (p[0], p[1], g[0], g[1]) for p, g in zip(pos, glyphs)))
    f.write('static const u8 font_u_a[%d * %d] = {   // grey 0..31 a texel\n' % (SW, SH))
    for r in range(SH): f.write('    ' + ','.join('%d' % v for v in sheet[r * SW:(r + 1) * SW]) + ',\n')
    f.write('};\n')
print('ui font: line %d, sheet %dx%d' % (NL, SW, SH))
