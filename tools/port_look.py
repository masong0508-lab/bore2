#!/usr/bin/env python3
"""Lift BORE (GBA) creature-builder code out of source/main.c into src/look_port.inc for BORE 2 (PS1).
The voxel logic (buildLook and friends) is pure C over look[] -> vox[][][]; only GBA attributes are stripped."""
import re, sys, os
SRC = sys.argv[1]           # path to bore-gba-main/source/main.c
OUT = sys.argv[2]           # src/look_port.inc
OUT_ENUM = os.path.join(os.path.dirname(OUT), "look_enum.inc")   # the enums the rest of the game shares (look.h)
lines = open(SRC, encoding='utf-8', errors='replace').read().split('\n')

def find(pat, start=0):
    for i in range(start, len(lines)):
        if pat.startswith('^'):
            if lines[i].rstrip() == pat[1:]: return i
        elif pat in lines[i]: return i
    raise SystemExit("not found: " + pat)

def rng(a_pat, b_pat, a_off=0, b_off=0, start=0):
    a = find(a_pat, start); b = find(b_pat, a)
    return lines[a + a_off:b + 1 + b_off]

out = []
def emit(title, chunk):
    out.append("// ---- %s (ported from BORE main.c) ----" % title)
    out.extend(chunk)

emit("tones", rng("#define NSW 8", "static const u16 botTones[NSW]"))
enum_lines = rng("enum { LK_SHAPE", "       LK_N };") + [lines[find("enum { AG_BABY")], lines[find("#define NSHAPE 30")], lines[find("enum { SH_AVG")], lines[find("#define NHAIR 15")], lines[find("enum { AS_FORTUNE")], lines[find("enum { TR_NEAT")], lines[find("enum { AB_SPEED")]]
emit("slider helpers", rng("static inline int lkSlide", "static inline int slideEff(int v)"))
emit("stages + shapes", rng("enum { AG_BABY", "#define BX0 ((W-BXW)/2)"))
emit("colour slots", rng("static u16 base[9+NWP]", "#define PANEL RGB(5,6,9)"))
emit("shade", rng("static inline __attribute__((always_inline)) u16 shade", "}", start=find("#define PANEL")))
emit("wallpaper + floor patterns", rng("typedef struct { const char*nm; u16 c[4]; const char*p[8]; } Tex;", "static u16 wpAvg[NWP];"))
emit("toneBy + setColors", rng("static u16 toneBy(u16 c,int e)", "^}", start=find("static u16 toneBy")) + rng("static void setColors(void) {", "^}", start=find("static void setColors(void)")))
emit("face art", rng("#define B9  \".........\"", "static inline u16 decSprBits(int n)"))
emit("body type draw tables", rng("static const signed char shpDraw[NSHAPE][4]", "{3,1,1,0},{1,-1,0,-1}") + rng("static const signed char shpEx[NSHAPE][6]", "{1,1,0,0,0,1},{0},{0,-1,0,-1,0,0}"))
emit("wedge masks", [lines[find("static const u8 wMask[8]")]])
emit("voxel grid + parts", rng("static u8 vox[H][D][W], ghost[H][D][W]", "static const Part parts[NPARTS]=", b_off=2))
emit("apply / doPart", rng("static void apply(int x0,int y0,int z0", "static void doPart(int act,int pi,int s,int x,int y,int z){", b_off=4))
emit("look -> blocks", rng("static int custom;   // 1 once the block builder", "static void restyle(int kind){", b_off=4))
emit("fixLook", rng("static int maskPick(int mask,int v,int n)", "static void clipCustom(void){", b_off=3))
emit("persona", rng("enum { AS_FORTUNE, AS_KNOW", "static void setSign(int s)"))
emit("abilities", rng("enum { AB_SPEED, AB_JUMP", "static const short partCost[NPART][4]"))

# the enums live in look_enum.inc (shared through look.h): drop them from the port so look.c sees each once
drop = set(enum_lines)
drop.add(lines[find("typedef struct { const char*nm; u16 c[4]; const char*p[8]; } Tex;")])   # tex.h holds it
out = [l for l in out if l not in drop]
text = '\n'.join(out)
open(OUT_ENUM, 'w').write("// GENERATED by tools/port_look.py: the BORE look / stage / shape enums, shared by every file through look.h\n" + '\n'.join(enum_lines) + "\n")
# strip GBA-isms
text = re.sub(r'\bEWRAM_BSS\b', '', text)
text = re.sub(r'\bIWRAM_(CODE|ARM|THUMB)\b', '', text)
text = text.replace('__attribute__((noinline)) ', '')
text = text.replace('__attribute__((always_inline)) ', '')
# the original checks the MASTER CONTROLLER cheat and the Konami unlock through xo[] / sUnlock / dbgOn: shimmed in look.c
open(OUT, 'w').write("// GENERATED by tools/port_look.py from BORE (GBA) source/main.c. Do not edit: edit the GBA source, re-run the tool.\n" + text + "\n")
print("wrote", OUT, len(text.split('\n')), "lines")
