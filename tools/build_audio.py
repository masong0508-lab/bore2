#!/usr/bin/env python3
"""BORE 2 audio build: every jukebox song (tracker .xm and streamed .adp sources) -> XA-ADPCM on the disc, 8 songs
interleaved per MUSICn.XA (2x speed, one channel each); the voice clips -> one SPU ADPCM blob (voices.bin).
usage: build_audio.py <bore-gba-main> <out dir>      (needs ffmpeg with libopenmpt, and xaenc on PATH)"""
import sys, os, re, json, subprocess, struct
SRC, OUT = sys.argv[1], sys.argv[2]
os.makedirs(OUT, exist_ok=True)
XAENC = 'xaenc'
RATE = int(os.environ.get('XA_RATE', '37800'))   # 37800 (2x speed) or 18900 (1x speed, half the disc space: the GBA mixed at 18157 Hz anyway)
SECTOR = 2336
CHANNELS = 8

def run(cmd, **kw):
    r = subprocess.run(cmd, **kw)
    if r.returncode: raise SystemExit("failed: " + ' '.join(cmd))

# ---- the song list (source/songs.h) and the artists ----
songs = []
for l in open(os.path.join(SRC, 'source/songs.h'), encoding='utf-8'):
    m = re.match(r'SONG_XM\((\w+),"([^"]*)","([^"]*)"\)', l)
    if m: songs.append(dict(id=m.group(1), name=m.group(2), path=os.path.join(SRC, m.group(3)), kind='xm'))
artists = {}
for l in open(os.path.join(SRC, 'source/artists.h'), encoding='utf-8'):
    m = re.match(r'ARTIST\("([^"]*)","([^"]*)"\)', l)
    if m: artists[m.group(1)] = m.group(2)

def ascii_name(s):   # the PS1 font is plain capitals
    t = s.upper()
    for a, b in (('Ê', 'E'), ('É', 'E'), ('È', 'E'), ('Á', 'A'), ('Ã', 'A'), ('Ó', 'O'), ('Ô', 'O'), ('Ñ', 'N'), ('Í', 'I'), ('Ú', 'U'), ('Ç', 'C')):
        t = t.replace(a, b)
    return ''.join(c if 32 <= ord(c) < 127 else '' for c in t)

# ---- render + encode each song ----
streams = []
for i, s in enumerate(songs):
    pcm = os.path.join(OUT, s['id'] + '.pcm')
    xa = os.path.join(OUT, s['id'] + ('.xa' if RATE == 37800 else '.xa18'))
    ch = i % CHANNELS
    if not os.path.exists(xa):
        print('rendering', s['name'], flush=True)
        run(['ffmpeg', '-v', 'error', '-y', '-i', s['path'], '-f', 's16le', '-ac', '2', '-ar', str(RATE), '-af', 'volume=0.9', pcm])
        with open(pcm, 'rb') as f:
            run([XAENC, 'xa', '1', str(RATE), '1', str(ch), xa], stdin=f)
        os.remove(pcm)
    data = open(xa, 'rb').read()
    n = len(data) // SECTOR
    s['sectors'] = n; s['file'] = i // CHANNELS; s['channel'] = ch
    s['seconds'] = n * 2016 // RATE
    streams.append(data)

# ---- interleave 8 per file ----
nfiles = (len(songs) + CHANNELS - 1) // CHANNELS
for f in range(nfiles):
    group = [(i, songs[i]) for i in range(f * CHANNELS, min(len(songs), (f + 1) * CHANNELS))]
    longest = max(s['sectors'] for _, s in group)
    out = bytearray()
    for k in range(longest):
        for ch in range(CHANNELS):
            idx = f * CHANNELS + ch
            if idx < len(songs) and k < songs[idx]['sectors']:
                out += streams[idx][k * SECTOR:(k + 1) * SECTOR]
            else:
                # a filler sector for this channel: no AUDIO flag, end of file, so the player knows the song is over
                sub = bytes([1, ch, 0xA0, 0x01]) * 2
                out += sub + bytes(SECTOR - 8)
    path = os.path.join(OUT, 'MUSIC%d.XA' % f)
    open(path, 'wb').write(out)
    print(path, len(out) // 1024 // 1024, 'MB', flush=True)

# ---- songs.inc ----
with open(os.path.join(OUT, 'songs.inc'), 'w') as w:
    w.write('// GENERATED by tools/build_audio.py: the jukebox, every BORE song on the disc\n')
    w.write('typedef struct { u8 file, channel; u16 seconds; const char *name, *artist; } SongRow;\n')
    w.write('#define NSONGS %d\n#define XA_RATE %d\n' % (len(songs), RATE))
    w.write('static const SongRow songs[NSONGS] = {\n')
    for s in songs:
        w.write('    { %d, %d, %d, "%s", "%s" },\n' % (s['file'], s['channel'], s['seconds'], ascii_name(s['name']), ascii_name(artists.get(s['name'], ''))))
    w.write('};\n')
total = sum(s['seconds'] for s in songs)
print('%d songs, %d min of music' % (len(songs), total // 60))

# ---- voices ----
VOICES = [('NEED', 'hey_i_need_something_h.wav'), ('AGREE', 'agree.wav'), ('ANGRY', 'angered.wav'), ('CRY', 'cry.wav'), ('DISAGREE', 'disagree.wav'),
          ('FINISHED', 'finished.wav'), ('FLIRT', 'flirt.wav'), ('HUNGRY', 'im_hungryrururyry.wav'), ('JOKE', 'joke_good.wav'), ('LAUGH', 'laughing.wav'),
          ('NAH', 'nah.wav'), ('PEE', 'need_to_pee.wav'), ('SHRIEK', 'shriek.wav'), ('SNORE', 'snoore.wav'), ('YAHOO', 'yahoo.wav'), ('YEHA', 'yeha.wav'),
          ('GROAN', 'cry_after_bad_event.wav'), ('WIN', 'win the fight.wav')]
RATE = 8000
blobs = []
for name, wav in VOICES:
    pcm = os.path.join(OUT, 'v_' + name + '.pcm'); adp = os.path.join(OUT, 'v_' + name + '.adpcm')
    run(['ffmpeg', '-v', 'error', '-y', '-i', os.path.join(SRC, 'tools/voices_src', wav), '-f', 's16le', '-ac', '1', '-ar', str(RATE), '-af', 'volume=1.4', pcm])
    with open(pcm, 'rb') as f:
        run([XAENC, 'spu', '0', adp], stdin=f)
    os.remove(pcm)
    blobs.append(open(adp, 'rb').read())
hdr_size = 4 + 12 * len(blobs)
hdr_size = (hdr_size + 15) & ~15
off = hdr_size
table = struct.pack('<I', len(blobs))
body = bytearray()
for b in blobs:
    pad = (16 - len(b) % 16) % 16
    table += struct.pack('<III', off, len(b), RATE)
    body += b + bytes(pad)
    off += len(b) + pad
table += bytes(hdr_size - len(table))
open(os.path.join(OUT, 'voices.bin'), 'wb').write(table + body)
print('voices.bin', (len(table) + len(body)) // 1024, 'KB')
