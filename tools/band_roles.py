#!/usr/bin/env python3
"""BORE 2 SUPERSTAR: which instrument of each band song belongs to which skill.
Every note in SONGS.BIN names its instrument (the XM instrument number - 1), so a part is told apart exactly, not guessed from the sound.
Roles: V voice, G guitar / bass (plucked and picked strings), K keys and melody (pads, piano, synths, bells, winds, strings), D drums and
percussion, F stage effects (risers, impacts: the sound desk plays them; always on).
Every instrument is looked at by name against RULES; a name no rule knows stops the build, so nothing is ever labelled by a default.
usage: band_roles.py <xm dir> [--list]"""
import sys, os, re
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import xm_parse
# (role, regex on the lower-case instrument name), first match wins
RULES = [
 ('F', r'^(riser|impact|sub drop|reverse swell|air swell|swell|zap|laser|air texture|boing|chalk|scratch|vinyl|reverse cymbal)'),
 ('D', r'(kick|snare|\bhat\b|hat closed|hat open|closed hat|open hat|tight hat|soft hat|dusty hat|metal hat|\bride\b|crash|cymbal|\btom\b|simmons tom|clap|\brim\b|rim click|rim snare|shaker|conga|congah|congal|\bperc\b|tambourine|cowbell|brush|woodblock|timbale|\briq\b|\btek\b|\bdum\b|frame drum|clave|gong|ghost|thump|timp|glitch)'),
 ('V', r'(\bvox\b|hyper vox|\bhoe\b|choir|\booh\b|\bahh\b|\bsung\b|whistle|^vx_)'),
 ('G', r'(bass|\bsub\b|reese|\b808\b|crushed 808|growl|\bacid|\b303\b|palm chug|12-string|\bchug|power chord|lead guitar|clean guitar|jazz guitar|\boud\b|oud low|oud high|kora|qanun|tanpura|nylon|^gt_|^ny_|^bs_|disco bass)'),
 ('K', r'(pad|piano|rhodes|\bclav\b|organ|hammond|mellotron|strings|violins|string|cello|ondes|synth|supersaw|\bstab|pluck|pizzicato|lead|\bbell|glock|marimba|vibes|xylophone|music box|metallophone|crystal|flute|\bney\b|duduk|brass|horn|\bsax\b|orchestra hit|hoover|electone|e-piano|dx7|chime|hook|8bit|arp|blip|whine|fm glass|glass|e-bow|quartal|^pad_|^st_|^fl_|^ce_|^pn_|^bell$)'),
]
def role_of(name):
    n = name.strip().lower()
    for r, rx in RULES:
        if re.search(rx, n): return r
    return None
# worthless_clouds' instruments are named "Sound N" in the file, so they are labelled from what the converter says they are
# (bore-gba-main tools/xm2gba.py make_clouds: role()): 7 lead, 1 and 9 arpeggios, 5 pad, 4 riff, 12 tick, 13 snare, 11 kick, 14 15 16 drum fills,
# 10 the sub pulse and fills, 17 stabs (a copy of 9), 18 19 hats (copies of 14 and 15), 20 the funk bass (a copy of 3).
# 6 is only played from E1 to E2 (the bass guitar's range), so it is the bass.
OVERRIDE = {'worthless_clouds': {1: 'K', 3: 'G', 4: 'K', 5: 'K', 6: 'G', 7: 'K', 9: 'K', 10: 'D', 11: 'D', 12: 'D', 13: 'D', 14: 'D', 15: 'D', 16: 'D', 17: 'K', 18: 'D', 19: 'D', 20: 'G'}}
ROLE_CODE = {'D': 1, 'G': 2, 'K': 3, 'V': 4, 'F': 5}   # 0: not played
def table(m, sid):
    used = set()
    for o in m['order']:
        for row in m['pats'][o]:
            for c in row:
                if c and c[0] and c[0] < 97: used.add(c[1])
    t = [0] * 32; bad = []; ov = OVERRIDE.get(sid, {})
    for i in sorted(used):
        if i > 32: bad.append(i); continue
        nm = m['insts'][i-1].name if i <= len(m['insts']) else ''
        r = ov.get(i) or (role_of(nm) if sid not in OVERRIDE else None)
        if r is None: bad.append((i, nm)); continue
        t[i-1] = ROLE_CODE[r]
    return t, bad
GENRES = ['TECHNO', 'ROCK', 'HIPHOP', 'HOUSE', 'HITECH', 'POP', 'BALLAD', 'DISCO', 'FUNK', 'JAZZ', 'CHILL', 'WORLD']
if __name__ == '__main__':
    d = sys.argv[1]; here = os.path.dirname(os.path.abspath(__file__))
    names = dict(re.findall(r'SONG_XM\((\w+),"([^"]*)"', open(os.path.join(d, '..', 'source', 'songs.h')).read()))
    lines = [l.split() for l in open(os.path.join(here, 'band_songs.txt')).read().split('\n') if l and not l.startswith('#')]
    out = ['// GENERATED by tools/band_roles.py: the 25 SUPERSTAR songs, and which skill plays each instrument of each (0 not played, 1 drums,',
           '// 2 guitar/bass, 3 keys, 4 voice, 5 stage effects). Indexed by the XM instrument number - 1 (the same index a note carries in SONGS.BIN).',
           'typedef struct { const char *song; u8 genre; u8 role[32]; } BandSong;', '#define NBANDSONG %d' % len(lines), 'static const BandSong bandsong[NBANDSONG] = {']
    allbad = 0
    for sid, genre in lines:
        m = xm_parse.read(os.path.join(d, sid + '.xm')); t, bad = table(m, sid)
        if bad: print('UNLABELLED', sid, bad); allbad += 1
        print('%-26s %-7s %s' % (sid, genre, ' '.join('%d:%s=%s' % (i+1, m['insts'][i].name.strip() if i < len(m['insts']) else '+', 'DGKVF'[v-1]) for i, v in enumerate(t) if v)))
        out.append('    { "%s", %d, { %s } },' % (names[sid], GENRES.index(genre), ','.join(map(str, t))))
    out.append('};')
    if allbad: sys.exit('stopped: %d songs have instruments no rule knows' % allbad)
    open(os.path.join(here, '..', 'src', 'band_roles.inc'), 'w').write('\n'.join(out) + '\n'); print('wrote src/band_roles.inc')
