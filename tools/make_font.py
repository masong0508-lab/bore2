#!/usr/bin/env python3
"""BORE's own smooth font (source/fontdata.h, 9 coverage steps) -> PS1 textures.
Coverage 8 = an opaque white texel; 1..7 = a semi-transparent (STP) grey, drawn additively, so the edges stay smooth.
Sizes: s (cap 5), m (cap 10) for the UI, l (cap 24) for the title's letters only.
usage: make_font.py <fontdata.h> <out fonttex.inc>"""
import re, sys
src = open(sys.argv[1], encoding='utf-8').read()
def arr(name):
    m = re.search(r'static const u(?:8|32) %s\[\d+\]=\{(.*?)\};' % name, src, re.S)
    return [int(v) for v in m.group(1).replace('\n', '').split(',') if v.strip()]
chars = re.search(r'#define FNT_CHARS "(.*)"', src).group(1).encode().decode('unicode_escape')
def const(n): return int(re.search(r'#define %s (\d+)' % n, src).group(1))
out = []
SHEET_W = 128
for size, keep in (('s', None), ('m', None), ('l', 'BORE2')):
    fo, fw, fa, fx, fp = arr('fo_' + size), arr('fw_' + size), arr('fa_' + size), arr('fx_' + size), arr('fp_' + size)
    fh, fsp, ftop = const('FH_' + size), const('FSP_' + size), const('FTOP_' + size)
    # pack
    x = y = 0; rowh = 0; sheet = {}
    glyphs = []
    for i, ch in enumerate(chars):
        if keep and ch not in keep: glyphs.append((0, 0, 0, fa[i])); continue
        w = fw[i]
        if x + w + 1 > SHEET_W: x = 0; y += rowh + 1; rowh = 0
        glyphs.append((x, y, w, fa[i]))
        g = fp[fo[i]:fo[i] + w * fh]
        for r in range(fh):
            for q in range(w):
                a = g[r * w + q]
                if a: sheet[(x + q, y + r)] = a
        x += w + 1; rowh = max(rowh, fh)
    H = y + rowh + 1
    px = []
    for r in range(H):
        for c in range(SHEET_W):
            a = sheet.get((c, r), 0)
            if a == 0: px.append(0)
            elif a >= 8: px.append(0x7fff)
            else:
                v = a * 31 // 8
                px.append(0x8000 | v | (v << 5) | (v << 10))
    out.append('#define FONT_%s_H %d\n#define FONT_%s_LINE %d\n#define FONT_%s_SPACE %d\n#define FONT_%s_TOP %d' % (size.upper(), H, size.upper(), fh, size.upper(), fsp, size.upper(), ftop))
    out.append('static const u8 font_%s_glyph[%d][4] = { %s };' % (size, len(glyphs), ', '.join('{%d,%d,%d,%d}' % g for g in glyphs)))
    out.append('static const u16 font_%s_px[%d * %d] = {' % (size, SHEET_W, H))
    for r in range(H): out.append('    ' + ','.join('0x%04x' % v for v in px[r * SHEET_W:(r + 1) * SHEET_W]) + ',')
    out.append('};')
    print(size, 'sheet', SHEET_W, 'x', H)
with open(sys.argv[2], 'w') as w:
    w.write('// GENERATED by tools/make_font.py from BORE source/fontdata.h: the smooth font as 128-wide texture sheets\n')
    w.write('#define FONT_CHARS "%s"\n#define FONT_SHEET_W 128\n' % chars.replace('\\', '\\\\').replace('"', '\\"'))
    w.write('\n'.join(out) + '\n')
