#!/usr/bin/env python3
# The FARM LIFE crop bed, coop, cow and stand: Build/Buy objects (src/items_farm.inc, included by items.c). Letters 0xDB..0xDE.
mats = {
 'pink':[(29,12,22),(27,10,20)], 'purple':[(14,6,22),(12,5,20)], 'white':[(29,29,28),(27,27,26)], 'yellow':[(31,26,6),(29,24,5)],
 'wood':[(17,11,6),(15,9,4)], 'gold':[(31,24,6),(28,20,4)], 'blue':[(8,14,28),(6,12,26)], 'red':[(26,5,5),(23,4,4)],
 'green':[(8,22,8),(6,20,6)], 'dark':[(5,4,8),(4,3,6)], 'glass':[(19,25,28),(22,27,30)], 'cloth':[(28,24,24),(26,22,22)], 'soil':[(12,8,4),(10,6,3)], 'leaf':[(6,24,6),(5,22,5)], 'orange':[(30,16,4),(27,14,3)], 'cream':[(30,28,22),(28,26,20)], 'pinkc':[(30,20,20),(28,18,18)], 'grey':[(12,12,14),(10,10,12)],
}
out = ['// GENERATED by tools/make_items_farm.py: FARM LIFE things (included by items.c)']
for k in ('soil','leaf','orange','cream','pinkc'):
    a,b = mats[k]
    out.append('static const u16 p_q_%s[2]={RGB(%d,%d,%d),RGB(%d,%d,%d)};' % ((k,)+a+b))
    out.append('MAT(q_%s,p_q_%s,2,2,"ab","ba")' % (k,k))
# (the materials q_* come from items_farm.inc, included first)
def B(x0,y0,x1,y1,z0,z1,m,top=None):
    mm = ['&q_%s' % (top or m)] + ['&q_%s' % m]*4
    return '{%d,%d,%d,%d,%d,%d,{%s}}' % (x0,y0,x1,y1,z0,z1,','.join(mm))
items = [
 ('CROP BED', 'F_ROT', 40, [B(0,0,8,8,0,2,'soil'), B(1,1,2,7,2,5,'leaf'), B(4,1,5,7,2,6,'leaf'), B(7,1,8,7,2,4,'leaf'), B(1,1,2,2,5,6,'orange')]),
 ('HEN COOP', 'F_ROT', 90, [B(0,1,8,7,0,1,'wood'), B(1,2,7,7,1,6,'red'), B(0,1,8,8,6,8,'wood'), B(3,1,5,2,1,4,'dark'), B(0,0,2,1,0,3,'cream'), B(6,0,8,1,0,2,'cream')]),
 ('DAIRY COW', 'F_ROT', 300, [B(1,1,7,7,0,1,'wood'), B(1,2,2,3,1,6,'white'), B(6,2,7,3,1,6,'white'), B(1,5,2,6,1,6,'white'), B(6,5,7,6,1,6,'white'), B(1,2,7,6,5,9,'white'), B(3,2,5,5,6,9,'dark'), B(3,0,5,2,6,9,'pinkc')]),
 ('FARM STAND', 'F_ROT', 150, [B(0,1,8,2,0,7,'wood'), B(0,0,8,5,5,6,'red'), B(1,2,7,6,0,4,'wood'), B(1,3,3,5,4,5,'orange'), B(4,3,6,5,4,6,'red'), B(0,0,8,1,6,8,'white')]),
]
defs = []
for i, (nm, fl, cost, bx) in enumerate(items):
    out.append('static const IBox bxFrm%d[%d]={%s};' % (i, len(bx), ','.join(bx)))
    defs.append('    { (char)0x%X, "%s", bxFrm%d, %d, 0, 0, %s, %d },   \\' % (0xDB+i, nm, i, len(bx), fl or '0', cost))
out.append('#define ITEMS_FARM \\')
out += defs
out.append('')
open('src/items_farm.inc', 'w').write('\n'.join(out) + '\n')
