# The PARTY pack: Build/Buy objects (src/items_party.inc, included by items.c). Letters 0xC7..0xCE.
mats = {
 'pink':[(29,12,22),(27,10,20)], 'purple':[(14,6,22),(12,5,20)], 'white':[(29,29,28),(27,27,26)], 'yellow':[(31,26,6),(29,24,5)],
 'wood':[(17,11,6),(15,9,4)], 'gold':[(31,24,6),(28,20,4)], 'blue':[(8,14,28),(6,12,26)], 'red':[(26,5,5),(23,4,4)],
 'green':[(8,22,8),(6,20,6)], 'dark':[(5,4,8),(4,3,6)], 'glass':[(19,25,28),(22,27,30)], 'cloth':[(28,24,24),(26,22,22)], 'grey':[(12,12,14),(10,10,12)],
}
out = ['// GENERATED by tools/make_items_party.py: the PARTY pack (included by items.c)']
for n, (a, b) in mats.items():
    out.append('static const u16 p_q_%s[2]={RGB(%d,%d,%d),RGB(%d,%d,%d)};' % (n, *a, *b))
    out.append('MAT(q_%s,p_q_%s,2,2,"ab","ba")' % (n, n))
out.append('static const u16 p_q_disco[3]={RGB(30,30,31),RGB(18,22,30),RGB(30,16,26)};')
out.append('MAT(q_disco,p_q_disco,4,4,"abca","bcab","cabc","abca")')
def B(x0,y0,x1,y1,z0,z1,m,top=None):
    mm = ['&q_%s' % (top or m)] + ['&q_%s' % m]*4
    return '{%d,%d,%d,%d,%d,%d,{%s}}' % (x0,y0,x1,y1,z0,z1,','.join(mm))
items = [
 ('DISCO BALL', 0, 180, [B(3,3,5,5,14,15,'grey'), B(2,2,6,6,8,14,'disco'), B(3,3,5,5,6,8,'disco')]),
 ('BUFFET TABLE', 'F_ROT', 140, [B(0,1,8,7,0,6,'wood'), B(0,0,8,8,6,7,'cloth'), B(1,2,3,5,7,9,'red'), B(3,2,5,5,7,10,'yellow'), B(5,2,7,5,7,9,'green')]),
 ('PUNCH BOWL', 0, 60, [B(2,2,6,6,0,5,'wood'), B(1,1,7,7,5,6,'cloth'), B(2,2,6,6,6,9,'glass'), B(3,3,5,5,6,8,'red')]),
 ('SPEAKER STACK', 'F_ROT', 220, [B(1,2,7,7,0,5,'dark'), B(1,2,7,7,5,10,'dark'), B(2,6,4,7,1,4,'grey'), B(4,6,6,7,1,4,'grey'), B(3,6,5,7,6,9,'grey')]),
 ('BALLOONS', 0, 30, [B(3,3,5,5,0,1,'grey'), B(3,3,4,4,1,8,'white'), B(1,1,4,4,8,12,'red'), B(4,1,7,4,9,13,'blue'), B(3,4,6,7,8,12,'yellow')]),
 ('DJ BOOTH', 'F_ROT', 350, [B(0,1,8,7,0,6,'dark'), B(1,2,4,6,6,7,'grey'), B(4,2,7,6,6,7,'grey'), B(1,2,4,6,7,8,'purple'), B(5,3,7,5,7,8,'pink')]),
 ('KARAOKE STAGE', 'F_ROT', 260, [B(0,0,8,8,0,2,'purple'), B(5,2,7,4,2,9,'grey'), B(5,2,7,4,9,11,'dark'), B(1,1,3,3,2,3,'gold')]),
 ('PHOTO BOOTH', 'F_ROT', 280, [B(0,1,8,7,0,12,'red'), B(1,2,7,7,1,10,'dark'), B(2,1,6,2,5,9,'white'), B(0,1,8,7,12,13,'yellow')]),
]
defs = []
for i, (nm, fl, cost, bx) in enumerate(items):
    out.append('static const IBox bxPty%d[%d]={%s};' % (i, len(bx), ','.join(bx)))
    defs.append('    { (char)0x%X, "%s", bxPty%d, %d, 0, 0, %s, %d },   \\' % (0xC7+i, nm, i, len(bx), fl or '0', cost))
out.append('#define ITEMS_PARTY \\')
out += defs
out.append('')
open('src/items_party.inc', 'w').write('\n'.join(out) + '\n')
